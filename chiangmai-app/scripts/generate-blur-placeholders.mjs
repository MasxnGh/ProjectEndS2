#!/usr/bin/env node
// Generates tiny base64 blur placeholders for every photo referenced in
// src/data/photo-manifest.ts and writes src/data/blur-manifest.ts so
// <PlaceImage placeholder="blur"> has a real blurDataURL to show instead of
// a blank frame while the full-size image loads.
//
// Usage: node scripts/generate-blur-placeholders.mjs

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

// photo-manifest.ts can't be imported directly by plain Node (no TS loader
// here), so extract the slug -> path pairs with a small regex instead.
const manifestSrc = await fs.readFile(path.join(ROOT, "src/data/photo-manifest.ts"), "utf8");
const entries = [...manifestSrc.matchAll(/"([^"]+)":\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]);
console.log(`Generating blur placeholders for ${entries.length} photos...`);

const results = {};
for (const [slug, publicPath] of entries) {
  const filePath = path.join(ROOT, "public", publicPath.replace(/^\//, ""));
  try {
    const buffer = await sharp(filePath)
      .resize(16, 16, { fit: "inside" })
      .jpeg({ quality: 40 })
      .toBuffer();
    results[slug] = `data:image/jpeg;base64,${buffer.toString("base64")}`;
    console.log(`  ok: ${slug}`);
  } catch (err) {
    console.warn(`  skip: ${slug} (${err.message})`);
  }
}

const output = `// Auto-generated by scripts/generate-blur-placeholders.mjs — do not edit by hand.
// Re-run "node scripts/generate-blur-placeholders.mjs" after refreshing photos.
const blurManifest: Record<string, string> = ${JSON.stringify(results, null, 2)};

export function getPlaceBlurDataURL(slug: string): string | undefined {
  return blurManifest[slug];
}

export default blurManifest;
`;

await fs.writeFile(path.join(ROOT, "src/data/blur-manifest.ts"), output);
console.log(`Wrote src/data/blur-manifest.ts with ${Object.keys(results).length} entries.`);
