#!/usr/bin/env node
/**
 * Regenerates the two files that tell the app which photos exist and who took
 * them, from what is actually on disk.
 *
 * Disk is the source of truth on purpose. The previous generator wrote the
 * manifest from its own download list, so when photos were later deleted the
 * manifest still pointed at them and pages rendered broken images. Reading the
 * directory means a photo removed by hand disappears from the site correctly,
 * and a credit for a photo we no longer publish is dropped rather than left to
 * claim something untrue on /credits.
 *
 * Usage: node scripts/generate-photo-data.mjs
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cleanArtist } from "./lib/commons-match.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IMAGE_DIRS = ["places", "guides"];

async function listSlugs(dir) {
  const full = path.join(ROOT, "public", "images", dir);
  try {
    const files = await fs.readdir(full);
    return files.filter((f) => f.endsWith(".jpg")).map((f) => f.replace(/\.jpg$/, ""));
  } catch {
    return [];
  }
}

async function main() {
  /** slug -> public path, in a stable order so the diff is readable. */
  const manifest = {};
  const onDisk = new Set();
  for (const dir of IMAGE_DIRS) {
    for (const slug of (await listSlugs(dir)).sort()) {
      manifest[slug] = `/images/${dir}/${slug}.jpg`;
      onDisk.add(slug);
    }
  }

  await fs.writeFile(
    path.join(ROOT, "src", "data", "photo-manifest.ts"),
    `// Auto-generated by scripts/generate-photo-data.mjs — do not edit by hand.\n` +
      `// Re-run "npm run generate:photos" after adding or removing an image.\n` +
      `const photoManifest: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n\n` +
      `export function getPlacePhoto(slug: string): string | undefined {\n` +
      `  return photoManifest[slug];\n}\n\nexport default photoManifest;\n`
  );

  // Credits come from the fetch run's record, narrowed to photos we still ship.
  let accepted = [];
  try {
    const raw = await fs.readFile(path.join(ROOT, "scripts", "commons-results.json"), "utf8");
    accepted = JSON.parse(raw).accepted ?? [];
  } catch {
    console.log("no commons-results.json — writing an empty credit list");
  }

  const credits = accepted
    .filter((a) => onDisk.has(a.slug))
    .sort((a, b) => a.slug.localeCompare(b.slug));

  const entries = credits
    .map(
      (a) =>
        `  ${JSON.stringify(a.slug)}: {\n` +
        `    artist: ${JSON.stringify(cleanArtist(a.artistRaw ?? a.artist))},\n` +
        `    licence: ${JSON.stringify(a.licence)},\n` +
        `    sourceUrl: ${JSON.stringify(a.descriptionUrl)},\n` +
        `    entity: ${JSON.stringify(a.entity)},\n  },`
    )
    .join("\n");

  const creditsPath = path.join(ROOT, "src", "data", "photo-credits.ts");
  const source = await fs.readFile(creditsPath, "utf8");
  const replaced = source.replace(
    /const photoCredits: Record<string, PhotoCredit> = \{[\s\S]*?\n\};/,
    `const photoCredits: Record<string, PhotoCredit> = {${entries ? "\n" + entries + "\n" : ""}};`
  );
  if (replaced === source && credits.length > 0) {
    throw new Error("could not find the photoCredits record to replace in photo-credits.ts");
  }
  await fs.writeFile(creditsPath, replaced);

  // MANUAL_CREDITS lives outside the generated block, so read it back to avoid
  // reporting a hand-credited photo as uncredited.
  const manual = [...replaced.matchAll(/^  "([a-z0-9-]+)": {$/gm)].map((m) => m[1]);
  const uncredited = [...onDisk].filter(
    (s) =>
      !credits.some((c) => c.slug === s) &&
      !manual.includes(s) &&
      !manifest[s].startsWith("/images/guides/")
  );
  console.log(`manifest: ${Object.keys(manifest).length} images`);
  console.log(`credits:  ${credits.length}`);
  if (uncredited.length > 0) {
    // Not fatal, but worth seeing: a published photo with no recorded source is
    // one nobody can check, which is the problem this pipeline exists to fix.
    console.log(`uncredited place photos: ${uncredited.join(", ")}`);
  }
}

main();
